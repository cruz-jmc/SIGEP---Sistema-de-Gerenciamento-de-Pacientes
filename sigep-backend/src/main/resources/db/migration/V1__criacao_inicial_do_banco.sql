-- Estrutura inicial correspondente aos mapeamentos JPA atuais.
-- Sem carga de dados e sem alteracoes destrutivas.

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL,
    primeiro_acesso BOOLEAN NOT NULL,
    criado_por BIGINT,
    criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (
        perfil IN ('COORDENADOR', 'FUNCIONARIO')
    ),
    CONSTRAINT fk_usuario_criador FOREIGN KEY (criado_por)
        REFERENCES usuario (id)
);

CREATE TABLE especialidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL,

    CONSTRAINT pk_especialidade PRIMARY KEY (id),
    CONSTRAINT uk_especialidade_nome UNIQUE (nome)
);

CREATE TABLE paciente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome_completo VARCHAR(200) NOT NULL,
    cpf VARCHAR(11) NOT NULL,
    data_nascimento DATE NOT NULL,
    cartao_sus VARCHAR(15) NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    endereco VARCHAR(300) NOT NULL,
    ubs_origem VARCHAR(200) NOT NULL,
    ativo BOOLEAN NOT NULL,
    cadastrado_por BIGINT,
    criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT pk_paciente PRIMARY KEY (id),
    CONSTRAINT uk_paciente_cpf UNIQUE (cpf),
    CONSTRAINT uk_paciente_cartao_sus UNIQUE (cartao_sus),
    CONSTRAINT fk_paciente_cadastrador FOREIGN KEY (cadastrado_por)
        REFERENCES usuario (id)
);

CREATE TABLE profissional (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(200) NOT NULL,
    conselho VARCHAR(200) NOT NULL,
    registro_conselho VARCHAR(50) NOT NULL,
    ativo BOOLEAN NOT NULL,
    cadastrado_por BIGINT,
    criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT pk_profissional PRIMARY KEY (id),
    CONSTRAINT uk_profissional_registro UNIQUE (registro_conselho),
    CONSTRAINT fk_profissional_cadastrador FOREIGN KEY (cadastrado_por)
        REFERENCES usuario (id)
);

CREATE TABLE profissional_especialidade (
    profissional_id BIGINT NOT NULL,
    especialidade_id BIGINT NOT NULL,

    CONSTRAINT pk_profissional_especialidade
        PRIMARY KEY (profissional_id, especialidade_id),
    CONSTRAINT fk_prof_esp_profissional FOREIGN KEY (profissional_id)
        REFERENCES profissional (id),
    CONSTRAINT fk_prof_esp_especialidade FOREIGN KEY (especialidade_id)
        REFERENCES especialidade (id)
);

CREATE TABLE escala_atendimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    grupo VARCHAR(255) NOT NULL,
    dia_semana SMALLINT NOT NULL,
    vigencia_inicio DATE NOT NULL,
    vigencia_fim DATE NOT NULL,
    pacientes_por_turno INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL,
    profissional_id BIGINT NOT NULL,
    especialidade_id BIGINT NOT NULL,

    CONSTRAINT pk_escala_atendimento PRIMARY KEY (id),
    CONSTRAINT ck_escala_grupo CHECK (
        grupo IN ('GRUPO_A', 'GRUPO_B')
    ),
    CONSTRAINT fk_escala_profissional FOREIGN KEY (profissional_id)
        REFERENCES profissional (id),
    CONSTRAINT fk_escala_especialidade FOREIGN KEY (especialidade_id)
        REFERENCES especialidade (id)
);

CREATE TABLE solicitacao_agendamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    grupo VARCHAR(255) NOT NULL,
    data_agendamento_inicial DATE NOT NULL,
    status_solicitacao VARCHAR(255) NOT NULL,
    motivo_rejeicao TEXT,
    criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    revisado_em TIMESTAMP(6) WITHOUT TIME ZONE,
    paciente_id BIGINT NOT NULL,
    especialidade_id BIGINT NOT NULL,
    profissional_solicitado_id BIGINT,
    cadastrado_por BIGINT NOT NULL,
    revisado_por BIGINT,

    CONSTRAINT pk_solicitacao_agendamento PRIMARY KEY (id),
    CONSTRAINT ck_solicitacao_grupo CHECK (
        grupo IN ('GRUPO_A', 'GRUPO_B')
    ),
    CONSTRAINT ck_solicitacao_status CHECK (
        status_solicitacao IN ('PENDENTE', 'APROVADA', 'REJEITADA')
    ),
    CONSTRAINT fk_solicitacao_paciente FOREIGN KEY (paciente_id)
        REFERENCES paciente (id),
    CONSTRAINT fk_solicitacao_especialidade FOREIGN KEY (especialidade_id)
        REFERENCES especialidade (id),
    CONSTRAINT fk_solicitacao_profissional FOREIGN KEY (profissional_solicitado_id)
        REFERENCES profissional (id),
    CONSTRAINT fk_solicitacao_cadastrador FOREIGN KEY (cadastrado_por)
        REFERENCES usuario (id),
    CONSTRAINT fk_solicitacao_revisor FOREIGN KEY (revisado_por)
        REFERENCES usuario (id)
);

CREATE TABLE plano_tratamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    status_plano VARCHAR(255) NOT NULL,
    aprovado_em TIMESTAMP(6) WITHOUT TIME ZONE,
    criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    solicitacao_id BIGINT NOT NULL,
    aprovado_por BIGINT NOT NULL,

    CONSTRAINT pk_plano_tratamento PRIMARY KEY (id),
    CONSTRAINT uk_plano_solicitacao UNIQUE (solicitacao_id),
    CONSTRAINT ck_plano_status CHECK (
        status_plano IN (
            'ATIVO',
            'CONCLUIDO',
            'CANCELADO_ABSENTEISMO'
        )
    ),
    CONSTRAINT fk_plano_solicitacao FOREIGN KEY (solicitacao_id)
        REFERENCES solicitacao_agendamento (id),
    CONSTRAINT fk_plano_aprovador FOREIGN KEY (aprovado_por)
        REFERENCES usuario (id)
);

CREATE TABLE agendamento_sessao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    plano_id BIGINT NOT NULL,
    escala_atendimento_id BIGINT NOT NULL,
    numero_sessao SMALLINT NOT NULL,
    data_agendada DATE NOT NULL,
    status VARCHAR(255) NOT NULL,
    status_presenca VARCHAR(255) NOT NULL,
    presenca_registrada_em TIMESTAMP(6) WITHOUT TIME ZONE,
    cancelado_em TIMESTAMP(6) WITHOUT TIME ZONE,
    motivo_cancelamento TEXT,
    criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    presenca_registrada_por BIGINT,

    CONSTRAINT pk_agendamento_sessao PRIMARY KEY (id),
    CONSTRAINT ck_sessao_status CHECK (
        status IN ('AGENDADA', 'CANCELADA_ABSENTEISMO')
    ),
    CONSTRAINT ck_sessao_presenca CHECK (
        status_presenca IN (
            'PENDENTE',
            'COMPARECEU',
            'FALTA_PENDENTE_JUSTIFICATIVA',
            'FALTA_JUSTIFICADA_POR_ATESTADO',
            'FALTA_NAO_JUSTIFICADA'
        )
    ),
    CONSTRAINT fk_sessao_plano FOREIGN KEY (plano_id)
        REFERENCES plano_tratamento (id),
    CONSTRAINT fk_sessao_escala FOREIGN KEY (escala_atendimento_id)
        REFERENCES escala_atendimento (id),
    CONSTRAINT fk_sessao_responsavel_presenca FOREIGN KEY (presenca_registrada_por)
        REFERENCES usuario (id)
);

CREATE TABLE cota_mensal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    mes_referencia SMALLINT NOT NULL,
    ano_referencia SMALLINT NOT NULL,
    quantidade_cota_limite INTEGER NOT NULL,
    especialidade_id BIGINT NOT NULL,
    profissional_id BIGINT NOT NULL,
    cadastrado_por BIGINT NOT NULL,

    CONSTRAINT pk_cota_mensal PRIMARY KEY (id),
    CONSTRAINT fk_cota_especialidade FOREIGN KEY (especialidade_id)
        REFERENCES especialidade (id),
    CONSTRAINT fk_cota_profissional FOREIGN KEY (profissional_id)
        REFERENCES profissional (id),
    CONSTRAINT fk_cota_cadastrador FOREIGN KEY (cadastrado_por)
        REFERENCES usuario (id)
);

CREATE TABLE data_disponivel_realocacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    data_disponivel DATE,
    status VARCHAR(255) NOT NULL,
    disponibilizada_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    realocada_em TIMESTAMP(6) WITHOUT TIME ZONE,
    escala_atendimento_id BIGINT NOT NULL,
    plano_origem_id BIGINT,
    agendamento_origem_id BIGINT,
    agendamento_destino_id BIGINT,
    cadastrado_por BIGINT NOT NULL,

    CONSTRAINT pk_data_disponivel_realocacao PRIMARY KEY (id),
    CONSTRAINT ck_realocacao_status CHECK (
        status IN ('DISPONIVEL', 'REALOCADA', 'CANCELADA')
    ),
    CONSTRAINT fk_realocacao_escala FOREIGN KEY (escala_atendimento_id)
        REFERENCES escala_atendimento (id),
    CONSTRAINT fk_realocacao_plano_origem FOREIGN KEY (plano_origem_id)
        REFERENCES plano_tratamento (id),
    CONSTRAINT fk_realocacao_sessao_origem FOREIGN KEY (agendamento_origem_id)
        REFERENCES agendamento_sessao (id),
    CONSTRAINT fk_realocacao_sessao_destino FOREIGN KEY (agendamento_destino_id)
        REFERENCES agendamento_sessao (id),
    CONSTRAINT fk_realocacao_cadastrador FOREIGN KEY (cadastrado_por)
        REFERENCES usuario (id)
);

CREATE TABLE notificacao_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo_notificacao VARCHAR(255) NOT NULL,
    mensagem TEXT NOT NULL,
    lida BOOLEAN NOT NULL,
    criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    lido_em TIMESTAMP(6) WITHOUT TIME ZONE,
    destinatario_id BIGINT NOT NULL,
    plano_id BIGINT,

    CONSTRAINT pk_notificacao_usuario PRIMARY KEY (id),
    CONSTRAINT ck_notificacao_tipo CHECK (
        tipo_notificacao IN (
            'REALOCACAO_NECESSARIA',
            'DATAS_DISPONIVEIS',
            'ALERTA_OITAVA_SESSAO'
        )
    ),
    CONSTRAINT fk_notificacao_destinatario FOREIGN KEY (destinatario_id)
        REFERENCES usuario (id),
    CONSTRAINT fk_notificacao_plano FOREIGN KEY (plano_id)
        REFERENCES plano_tratamento (id)
);

CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id BIGINT NOT NULL,
    tabela_nome VARCHAR(100) NOT NULL,
    registro_id BIGINT NOT NULL,
    acao VARCHAR(50) NOT NULL,
    dados_anteriores JSONB,
    dados_novos JSONB,
    criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT pk_auditoria PRIMARY KEY (id),
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuario (id)
);
