CREATE TABLE convite_ativacao (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                  usuario_id BIGINT NOT NULL,
                                  token_hash VARCHAR(64) NOT NULL,
                                  expira_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
                                  utilizado_em TIMESTAMP(6) WITHOUT TIME ZONE,
                                  criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

                                  CONSTRAINT pk_convite_ativacao PRIMARY KEY (id),

                                  CONSTRAINT fk_convite_ativacao_usuario
                                      FOREIGN KEY (usuario_id)
                                          REFERENCES usuario (id),

                                  CONSTRAINT uk_convite_ativacao_token_hash
                                      UNIQUE (token_hash)
);

CREATE INDEX idx_convite_ativacao_usuario
    ON convite_ativacao (usuario_id);
